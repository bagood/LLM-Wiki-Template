"""Validate before deterministically replacing generated navigation only."""
from pathlib import Path
from urllib.parse import quote
import argparse
import json
import sys
from common import ContractError, atomic_write, read_page, validate

HEADER = "<!-- GENERATED by build_index_md.py; edit page metadata instead. -->\n"


def label(value):
    return " ".join(str(value).split()).replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]")


def render_indexes(bundle):
    bundle = Path(bundle)
    directories = {bundle} | {p.parent for p in bundle.rglob("*.md") if p.name not in {"index.md", "log.md"}}
    for directory in list(directories):
        directories.update(p for p in directory.parents if p.is_relative_to(bundle))
    rendered = {}
    for directory in sorted(directories):
        text = ('---\nokf_version: "0.2"\n---\n\n' if directory == bundle else "") + HEADER
        text += f"\n# {label(directory.name if directory != bundle else 'Wiki')}\n\n"
        entries = []
        for path in sorted(directory.iterdir()):
            if path.is_dir() and path in directories:
                entries.append(f"- [{label(path.name.title())}]({quote(path.name)}/index.md) - Browse {label(path.name)}.")
            elif path.is_file() and path.suffix == ".md" and path.name not in {"index.md", "log.md"}:
                fm, _ = read_page(path)
                entries.append(f"- [{label(fm.get('title') or path.stem)}]({quote(path.name)}) - {label(fm.get('description') or '')}")
        text += "\n".join(entries) + "\n" if entries else "_No knowledge pages yet._\n"
        rendered[directory / "index.md"] = text
    return rendered


def build(workspace):
    workspace = Path(workspace).resolve()
    report = validate(workspace, check_indexes=False)
    if not report["valid"]:
        raise ContractError(json.dumps(report))
    bundle = workspace / "wiki"
    rendered = render_indexes(bundle)
    # Check every overwrite before writing anything. Handwritten indexes are protected.
    for path in bundle.rglob("index.md"):
        if HEADER.strip() not in path.read_text(encoding="utf-8"):
            raise ContractError(f"refusing to replace handwritten index: {path}")
    for path, text in rendered.items():
        atomic_write(path, text)
    for path in bundle.rglob("index.md"):
        if path not in rendered:
            path.unlink()
    return {"indexes": [p.relative_to(workspace).as_posix() for p in rendered], "warnings": report["warnings"]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--wiki-dir", required=True)
    args = parser.parse_args()
    try:
        print(json.dumps(build(args.wiki_dir), indent=2))
        return 0
    except (ContractError, OSError, ValueError) as exc:
        print(json.dumps({"error": str(exc)}), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
